#!/usr/bin/env python3
"""Regenerate TranslationCoverage.kt: per-language share of human vs machine-drafted strings.
Human = keys in values-<loc>/strings*.xml except strings_machine_translated.xml; machine = keys in
that file; the rest falls back to English. Run after any translation change, then commit."""
import os, glob, re
from i18n_lib import RES, base_strings, parse, locales
base = set(base_strings())
rows = []
for loc in locales():
    d = os.path.join(RES, 'values-' + loc)
    human, machine = set(), set()
    for f in glob.glob(os.path.join(d, '*.xml')):
        ks = set(parse(f))
        (machine if f.endswith('strings_machine_translated.xml') else human).update(ks)
    human &= base; machine = (machine & base) - human
    tag = re.sub(r'-r([A-Z]{2})$', r'-\1', loc)
    tag = {'iw': 'he', 'in': 'id'}.get(tag, tag)
    rows.append((tag, round(100 * len(human) / len(base)), round(100 * len(machine) / len(base))))
out = os.path.join(RES, '..', 'java', 'af', 'shizuku', 'manager', 'utils', 'TranslationCoverage.kt')
body = ''.join(f'        "{t}" to intArrayOf({h}, {m}),\n' for t, h, m in rows)
open(out, 'w', encoding='utf-8').write(f'''package af.shizuku.manager.utils

import java.util.Locale

/** GENERATED by scripts/i18n/coverage.py - do not edit. Percent of strings per language. */
object TranslationCoverage {{
    /** tag -> [human %, machine-drafted %]; anything left over shows English. */
    private val table = mapOf(
{body}    )

    /** Returns [human, machine] percent, or null for English / unknown languages. */
    fun of(locale: Locale): IntArray? {{
        val full = locale.toLanguageTag()
        return table[full] ?: table[locale.language]
    }}
}}
''')
print(len(rows), 'languages')
