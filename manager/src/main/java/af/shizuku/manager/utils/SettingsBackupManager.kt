    /** Privileged values the last import held back instead of switching on. */
    @Volatile
    var heldBack: Map<String, Any> = emptyMap()
        private set

    /**
     * Makes restored settings take effect now, without restarting the app. Most settings are read
     * when a screen opens; these are applied by code that normally runs only when the user changes
     * them in Settings, so a plain import left them on the old value until a restart.
     */
    fun applyRestoredLive(context: Context) {
        val app = context.applicationContext
        val prefs = ShizukuSettings.getPreferences() ?: return
        runCatching {
            androidx.appcompat.app.AppCompatDelegate
                .setDefaultNightMode(ShizukuSettings.getNightMode())
        }
        runCatching {
            val tag = ShizukuSettings.getRawLanguageTag()
            val locales =
                if (tag.isNullOrEmpty() || tag == "SYSTEM") {
                    androidx.core.os.LocaleListCompat
                        .getEmptyLocaleList()
                } else {
                    androidx.core.os.LocaleListCompat
                        .forLanguageTags(tag)
                }
            androidx.appcompat.app.AppCompatDelegate
                .setApplicationLocales(locales)
        }
        runCatching {
            if (prefs.contains(ShizukuSettings.Keys.KEY_START_ON_BOOT)) {
                ShizukuSettings.setStartOnBoot(app, prefs.getBoolean(ShizukuSettings.Keys.KEY_START_ON_BOOT, true))
            }
        }
        runCatching { AppAliasManager.applyAlias(app, ShizukuSettings.getAppIconAlias()) }
        runCatching {
            if (ShizukuSettings.getWatchdog()) {
                af.shizuku.manager.service.WatchdogService
                    .start(app)
            }
        }
        ShizukuSettings.syncAllPlusFeaturesToServer()
    }

    /** Applies (after the user confirmed) the privileged values the last import held back. */
    fun applyHeldBack() {
        val pending = heldBack
        heldBack = emptyMap()
        if (pending.isEmpty()) return
        val editor = ShizukuSettings.getPreferences()?.edit() ?: return
        pending.forEach { (key, v) ->
            when (v) {
                is Boolean -> editor.putBoolean(key, v)
                is String -> editor.putString(key, v)
            }
        }
        editor.apply()
        ShizukuSettings.syncAllPlusFeaturesToServer()
    }

    fun discardHeldBack() {
        heldBack = emptyMap()
    }

    /**
     * @param trustPrivileged applies [PRIVILEGED_KEYS] as stored instead of holding them back. Only
     * for settings that are already this user's on this device: the app's own force-update backup
     * and the signature-checked other flavor. A file the user picks, or a cloud restore, still asks.
     */
    fun import(
        @Suppress("UNUSED_PARAMETER") context: Context,
        json: String,
        trustPrivileged: Boolean = false,
    ): Boolean =
        importInternal(json, synchronous = false, trustPrivileged = trustPrivileged)

    /**
     * Like [import] but uses [SharedPreferences.Editor.commit] (synchronous disk write). Use this
     * from a [android.app.backup.BackupAgent] where the OS may start the app immediately after
     * the agent returns — [apply]'s async write could race with the first read on the new process.
     */
    fun importAndCommit(
        @Suppress("UNUSED_PARAMETER") context: Context,
        json: String,
        trustPrivileged: Boolean = false,
    ): Boolean =
        importInternal(json, synchronous = true, trustPrivileged = trustPrivileged)

    /** Settings left out of the reinstall copy: it is world-readable in /data/local/tmp. */
    private val REINSTALL_COPY_SECRET_KEYS =
        setOf(
            ShizukuSettings.Keys.KEY_VIRUSTOTAL_API_KEY,
            ShizukuSettings.Keys.KEY_PITHUS_API_KEY,
            // Which apps are hidden from other apps: readable here, it would defeat the point.
            ShizukuSettings.Keys.KEY_SHADOW_BINDER_HIDDEN_PACKAGES,
        )

    /** Set once this install has checked for a backup to restore; excluded from backups. */
    const val KEY_RESTORE_CHECKED = "backup_restore_checked"

    /** Set once the backup copies older builds left in Downloads have been removed. */
    private const val KEY_LEGACY_COPIES_REMOVED = "legacy_backup_copies_removed"

    @Volatile
    private var lastReinstallCopyHash = 0

    /** True if applying [json] would change nothing (e.g. this install's own older snapshot). */
    fun matchesCurrent(
        context: Context,
        json: String,
    ): Boolean =
        runCatching {
            val backup = JSONObject(json)
            val current = JSONObject(export(context))
            val keys =
                backup
                    .keys()
                    .asSequence()
                    .filter { it != VERSION_KEY && it !in EXCLUDED_KEYS }
                    .toList()
            keys.all { k -> current.has(k) && current.get(k).toString() == backup.get(k).toString() }
        }.getOrDefault(false)

    fun isRestoreChecked(): Boolean = runCatching { ShizukuSettings.getPreferences().getBoolean(KEY_RESTORE_CHECKED, false) }.getOrDefault(false)

    fun markRestoreChecked() {
        runCatching {
            ShizukuSettings
                .getPreferences()
                .edit()
                .putBoolean(KEY_RESTORE_CHECKED, true)
                .apply()
        }
    }

    /**
     * Keeps the copy that lets settings survive an uninstall/reinstall: /data/local/tmp, written as
     * shell through Shizuku. Only shell or root can write there, so a restore can trust it, unlike
     * public Downloads, where any app could plant a file. Apps can read it, so secrets such as
     * scanner API keys are left out (re-enter them after a reinstall).
     *
     * Nothing is written until this install has checked for a backup to restore: on a fresh
     * install the startup save would otherwise replace the surviving copy with defaults first.
     */

    private val backupRequests =
        kotlinx.coroutines.flow.MutableSharedFlow<Context>(
            extraBufferCapacity = 1,
            onBufferOverflow = kotlinx.coroutines.channels.BufferOverflow.DROP_OLDEST,
        )

    @OptIn(kotlinx.coroutines.FlowPreview::class)
    private val backupWriter by lazy {
        kotlinx.coroutines
            .CoroutineScope(kotlinx.coroutines.SupervisorJob() + kotlinx.coroutines.Dispatchers.IO)
            .launch { backupRequests.debounce(BACKUP_DEBOUNCE_MS).collect { saveAutoBackup(it) } }
    }

    /**
     * Saves the reinstall copy once things settle. Every settings change and every screen
     * leaving asks for one; writing each time started a privileged shell per change, and
     * overlapping writes raced on the same temp file.
     */
    fun requestAutoBackup(context: Context) {
        backupWriter
        backupRequests.tryEmit(context.applicationContext)
    }

    private const val BACKUP_DEBOUNCE_MS = 2_000L

    /** [json] without the settings that must not sit in a file other apps can read. */
    fun withoutSecrets(json: String): String = JSONObject(json).apply { REINSTALL_COPY_SECRET_KEYS.forEach { remove(it) } }.toString(2)

    fun saveAutoBackup(context: Context) {
        try {
            if (!isRestoreChecked()) return
            val json = export(context)
            if (json.isBlank() || json == "{}" || json.length < 20) return
            if (!runCatching { rikka.shizuku.Shizuku.pingBinder() }.getOrDefault(false)) return
            removeLegacyCopies(context)
            val sanitized = withoutSecrets(json)
            val hash = sanitized.hashCode()
            if (hash == lastReinstallCopyHash) return
            val dir = UpdateInstaller.REINSTALL_BACKUP_DIR
            val target = UpdateInstaller.reinstallBackupFile(context).absolutePath
            val script = "mkdir -p $dir && chmod 755 $dir && cat > $target.tmp && chmod 644 $target.tmp && mv -f $target.tmp $target"
            val process = rikka.shizuku.Shizuku.newProcess(arrayOf("sh", "-c", script), null, null)
            process.outputStream.use { it.write(sanitized.toByteArray()) }
            if (process.waitFor() == 0) lastReinstallCopyHash = hash
        } catch (e: Exception) {
            Timber.w(e, "Failed to persist auto backup")
        }
    }

    /**
     * Older builds wrote a copy to public Downloads (and this app's own Download folder) on every
     * launch (#651). The reinstall copy replaced them, so remove the leftovers once, as shell, which
     * can delete them whichever install created them. Only after the restore check, so a copy the
     * user still wanted to restore from has been offered first.
     */
    private fun removeLegacyCopies(context: Context) {
        val prefs = ShizukuSettings.getPreferences() ?: return
        if (prefs.getBoolean(KEY_LEGACY_COPIES_REMOVED, false)) return
        val files =
            UpdateInstaller.publicBackupCandidates().map { it.absolutePath }.distinct() +
                listOfNotNull(
                    context
                        .getExternalFilesDir(android.os.Environment.DIRECTORY_DOWNLOADS)
                        ?.let { java.io.File(it, UpdateInstaller.AUTO_BACKUP_FILENAME).absolutePath },
                )
        // One attempt: retrying a failing rm would start a shell on every activity stop.
        prefs.edit().putBoolean(KEY_LEGACY_COPIES_REMOVED, true).apply()
        runCatching {
            rikka.shizuku.Shizuku
                .newProcess(arrayOf("rm", "-f") + files, null, null)
                .waitFor()
        }
    }

    private fun importInternal(
        json: String,
        synchronous: Boolean,
        trustPrivileged: Boolean = false,
    ): Boolean {
        return try {
            val obj = JSONObject(json)
            val version = obj.optInt(VERSION_KEY, -1)
            if (version < 1) return false

            val prefs = ShizukuSettings.getPreferences() ?: return false
            val editor = prefs.edit()

            val held = mutableMapOf<String, Any>()
            val keys = obj.keys()
            while (keys.hasNext()) {
                val key = keys.next()
                if (key == VERSION_KEY || key in EXCLUDED_KEYS) continue
                if (key in PRIVILEGED_KEYS && !trustPrivileged) {
                    // Switching one off is safe to apply; switching one on (or pointing the su path
                    // somewhere) waits for the user's confirmation.
                    when (val v = obj.get(key)) {
                        false -> editor.putBoolean(key, false)
                        true -> if (!prefs.getBoolean(key, false)) held[key] = true
                        is String -> if (v.isNotEmpty() && v != prefs.getString(key, "")) held[key] = v
                    }
                    continue
                }
                when (val v = obj.get(key)) {
                    is Boolean -> editor.putBoolean(key, v)
                    is Int -> editor.putInt(key, v)
                    is Long -> editor.putLong(key, v)
                    is Double -> editor.putFloat(key, v.toFloat())
                    is String -> editor.putString(key, v)
                    is org.json.JSONArray -> {
                        val set = (0 until v.length()).map { v.getString(it) }.toSet()
                        editor.putStringSet(key, set)
                    }
                }
            }
            // A backup with no Watchdog setting is from a build that read absent as off (or from a
            // new install before its first server start): restore that off, rather than let this
            // install's pending new-install default turn the Watchdog on at its first start.
            if (!obj.has(ShizukuSettings.Keys.KEY_WATCHDOG) && !prefs.contains(ShizukuSettings.Keys.KEY_WATCHDOG)) {
                editor.putBoolean(ShizukuSettings.Keys.KEY_WATCHDOG, false)
            }
            heldBack = held
            val written =
                if (synchronous) {
                    editor.commit()
                } else {
                    editor.apply()
                    true
                }
            // Old backups carry the pre-merge corner keys.
            ShizukuSettings.migrateCornerSettingsIfNeeded()
            ShizukuSettings.syncAllPlusFeaturesToServer()
            written
        } catch (e: Exception) {
            false
        }
    }
}
